export const enUi = Object.fromEntries(Object.keys(esUi).map((key) => [key, key]))

export function translateUiText(text, locale, values = {}, remoteUi = null) {
  if (typeof text !== 'string') return text
  let translated = locale === 'es' ? remoteUi?.[text] || esUi[text] || text : text
  if (locale === 'es') {
    const approval = /^(.+) marked (approved|rejected|pending)\.$/.exec(text)
    if (approval) return `${approval[1]}: estado ${esUi[approval[2]]}.`
  }
  for (const [key, value] of Object.entries(values)) translated = translated.replaceAll(`{${key}}`, String(value))
  return translated
}
