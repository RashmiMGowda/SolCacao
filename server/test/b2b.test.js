const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { randomUUID } = require('node:crypto')

test('B2B workflow: authorization, validation, persistence, attachments, approval, quotation and response', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'solcacao-b2b-test-'))
  process.env.AUTH_DATA_PATH = path.join(directory, 'users.json')
  process.env.B2B_DATA_DIR = path.join(directory, 'b2b')
  process.env.USE_MOCK_AUTH_REPOSITORY = 'true'
  process.env.NODE_ENV = 'test'
  process.env.BCRYPT_ROUNDS = '4'
  await fs.writeFile(process.env.AUTH_DATA_PATH, '[]')
  const { app } = require('../src/app')
  let server = app.listen(0, '127.0.0.1')
  await new Promise(resolve => server.once('listening', resolve))
  let base = `http://127.0.0.1:${server.address().port}/api`
  t.after(async () => {
    await new Promise(resolve => server.close(resolve))
    assert.ok(path.resolve(directory).startsWith(`${path.resolve(os.tmpdir())}${path.sep}solcacao-b2b-test-`))
    await fs.rm(directory, { recursive: true, force: true })
  })
  const call = (route, token, body, method = body === undefined ? 'GET' : 'POST') => fetch(`${base}${route}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
  const login = async email => {
    const response = await call('/auth/login', null, { email, password: 'Password123!' })
    assert.equal(response.status, 200)
    return (await response.json()).token
  }
  const health = await call('/health')
  assert.equal(health.status, 200)
  assert.equal((await health.json()).status, 'ok')
  const business = await login('business@solcacao.test')
  const retail = await login('customer@solcacao.test')
  const pending = await login('pending@solcacao.test')
  const admin = await login('admin@solcacao.test')
  assert.equal((await call('/b2b/requests')).status, 401)
  assert.equal((await call('/b2b/requests', retail)).status, 403)
  assert.equal((await call('/b2b/requests', pending)).status, 403)
  const payload = { requestId: randomUUID(), cacaoProfile: 'Peru 80%', quantityKg: 25, brandName: 'Test Program', designDetails: 'Custom mold', packagingOption: 'Event Sleeve', whiteLabel: 'company-branding', specialInstructions: 'Gold logo', attachment: { name: 'design.svg', type: 'image/svg+xml', data: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"></svg>').toString('base64') } }
  assert.equal((await call('/b2b/requests', business, { ...payload, quantityKg: 4 })).status, 400)
  assert.equal((await call('/b2b/requests', business, { ...payload, quantityKg: 5.5 })).status, 400)
  assert.equal((await call('/b2b/requests', business, { ...payload, cacaoProfile: 'invalid' })).status, 400)
  assert.equal((await call('/b2b/requests', business, { ...payload, attachment: { ...payload.attachment, name: '../escape.svg' } })).status, 400)
  assert.equal((await call('/b2b/requests', business, { ...payload, attachment: { ...payload.attachment, type: 'image/png' } })).status, 400)
  assert.equal((await call('/b2b/requests', business, { ...payload, attachment: { ...payload.attachment, data: 'not-base64' } })).status, 400)
  assert.equal((await call('/b2b/requests', admin, payload)).status, 403)
  const response = await call('/b2b/requests', business, payload)
  assert.equal(response.status, 201, await response.clone().text())
  const saved = (await response.json()).request
  assert.equal(saved.status, 'SUBMITTED')
  assert.equal(saved.files.length, 1)
  assert.equal(saved.files[0].storagePath, undefined)
  await Promise.all([call('/b2b/requests', business, payload), call('/b2b/requests', business, payload)])
  assert.equal((await (await call('/b2b/requests', business)).json()).requests.length, 1)
  const download = await call(`/b2b/requests/${saved.id}/files/${saved.files[0].id}`, business)
  assert.equal(download.status, 200)
  assert.match(download.headers.get('content-disposition'), /attachment/)
  assert.equal(await download.text(), '<svg xmlns="http://www.w3.org/2000/svg"></svg>')
  assert.equal((await call(`/b2b/requests/${saved.id}/quote`, business, {})).status, 403)
  assert.equal((await call(`/b2b/requests/${saved.id}/review`, admin, {})).status, 200)
  const quote = { amountCents: 85000, validUntil: new Date(Date.now() + 86400000).toISOString(), notes: 'Four-week production estimate' }
  assert.equal((await call(`/b2b/requests/${saved.id}/quote`, admin, { ...quote, amountCents: -1 })).status, 400)
  assert.equal((await call(`/b2b/requests/${saved.id}/quote`, admin, { ...quote, validUntil: '2020-01-01' })).status, 400)
  assert.equal((await call(`/b2b/requests/${saved.id}/quote`, admin, quote)).status, 200)
  assert.equal((await call(`/b2b/requests/${saved.id}/quote`, admin, quote)).status, 409)
  const quoted = (await (await call(`/b2b/requests/${saved.id}`, business)).json()).request
  assert.equal(quoted.quote.amountCents, 85000)
  assert.equal((await call(`/b2b/requests/${saved.id}/respond`, business, { decision: 'ACCEPTED' })).status, 200)
  assert.equal((await call(`/b2b/requests/${saved.id}/respond`, business, { decision: 'DECLINED' })).status, 409)
  assert.equal((await call('/b2b/accounts', business)).status, 403)
  assert.equal((await call('/b2b/accounts/usr-b2b-pending/approval', admin, { status: 'REJECTED', reason: '' })).status, 400)
  assert.equal((await call('/b2b/accounts/usr-b2b-pending/approval', admin, { status: 'APPROVED' })).status, 200)
  assert.equal((await call(`/b2b/requests/${saved.id}`, pending)).status, 404)
  assert.equal((await call(`/b2b/requests/${saved.id}/files/${saved.files[0].id}`, pending)).status, 404)
  assert.equal((await call(`/b2b/requests/${saved.id}/respond`, pending, { decision: 'ACCEPTED' })).status, 404)
  const second = { ...payload, requestId: randomUUID(), attachment: null }
  assert.equal((await call('/b2b/requests', pending, second)).status, 201)
  assert.equal((await call(`/b2b/requests/${second.requestId}/quote`, admin, quote)).status, 200)
  assert.equal((await call(`/b2b/requests/${second.requestId}/respond`, pending, { decision: 'DECLINED' })).status, 200)
  const third = { ...payload, requestId: randomUUID(), attachment: undefined, attachments: [payload.attachment, { ...payload.attachment, name: 'second.svg' }] }
  const thirdResponse = await call('/b2b/requests', business, third)
  assert.equal(thirdResponse.status, 201)
  assert.equal((await thirdResponse.json()).request.files.length, 2)
  assert.equal((await call('/b2b/requests', business, { ...third, requestId: randomUUID(), attachments: Array(6).fill(payload.attachment) })).status, 400)
  assert.equal((await call(`/b2b/requests/${third.requestId}/quote`, admin, quote)).status, 200)
  const storePath = path.join(process.env.B2B_DATA_DIR, 'requests.json')
  const store = JSON.parse(await fs.readFile(storePath, 'utf8'))
  store.find(item => item.id === third.requestId).quote.validUntil = '2020-01-01T00:00:00Z'
  await fs.writeFile(storePath, JSON.stringify(store))
  assert.equal((await call(`/b2b/requests/${third.requestId}/respond`, business, { decision: 'ACCEPTED' })).status, 409)
  assert.equal((await call(`/b2b/requests/${third.requestId}/quote`, admin, quote)).status, 200)
  assert.equal((await call(`/b2b/requests/${third.requestId}/respond`, business, { decision: 'ACCEPTED' })).status, 200)
  await new Promise(resolve => server.close(resolve))
  server = app.listen(0, '127.0.0.1')
  await new Promise(resolve => server.once('listening', resolve))
  base = `http://127.0.0.1:${server.address().port}/api`
  const persisted = (await (await call(`/b2b/requests/${saved.id}`, business)).json()).request
  assert.equal(persisted.status, 'ACCEPTED')
  assert.deepEqual(persisted.history.map(event => event.status), ['SUBMITTED', 'UNDER_REVIEW', 'QUOTED', 'ACCEPTED'])
  assert.equal((await call(`/b2b/requests/${saved.id}/files/${saved.files[0].id}`, business)).status, 200)
  assert.equal((await (await call('/b2b/requests', admin)).json()).requests.length, 3)
  const accounts = (await (await call('/b2b/accounts', admin)).json()).accounts
  assert.ok(accounts.every(account => !account.passwordHash && !account.passwordResetTokens))
  assert.equal((await call('/b2b/accounts/usr-b2b-approved/approval', admin, { status: 'REJECTED', reason: 'Test approval revocation' })).status, 200)
  assert.equal((await call('/b2b/requests', business)).status, 403)
  const registration = await call('/auth/register', null, { accountType: 'B2B', firstName: 'New', lastName: 'Partner', email: 'newpartner@solcacao.test', phone: '555-0123', password: 'Password123!', confirmPassword: 'Password123!', corporatePartner: { companyName: 'New Partner Hotel', industry: 'Hotel / Hospitality', businessPhone: '555-0123', website: '' } })
  assert.equal(registration.status, 201)
  const registered = await registration.json()
  assert.equal(registered.user.corporatePartner.approvalStatus, 'PENDING')
  assert.equal((await call('/b2b/requests', registered.token)).status, 403)
  assert.equal((await call(`/b2b/accounts/${registered.user.id}/approval`, admin, { status: 'REJECTED', reason: 'Please add business details.' })).status, 200)
  const update = await call('/auth/me', registered.token, { firstName: 'New', lastName: 'Partner', email: 'newpartner@solcacao.test', phone: '555-0123', corporatePartner: { companyName: 'New Partner Hotel', industry: 'Hotel / Hospitality', businessPhone: '555-0123', website: '' } }, 'PUT')
  assert.equal(update.status, 200)
  assert.equal((await update.json()).user.corporatePartner.approvalStatus, 'PENDING')
  assert.equal((await call(`/b2b/accounts/${registered.user.id}/approval`, admin, { status: 'APPROVED' })).status, 200)
  assert.equal((await call('/b2b/requests', registered.token, { ...payload, requestId: randomUUID(), attachment: null })).status, 201)
})
